"""Реестр требований из прозы ПД.

ВАЖНАЯ ОГОВОРКА (Г.36): регулярки этого модуля подобраны и проверены на
ОДНОМ реальном документе. Это НЕ общий механизм — предметная
поправка прямо об этом: пример был иллюстрацией, не спецификацией, и
других типов документов будет много, с другими разделами и другой прозой.
Держать этот модуль как единственный узкий запасной путь для прогона БЕЗ
модели (режим `--no-llm`) — там и остаётся полезным, потому что альтернатива
без модели — вообще ничего не извлечь. Но общий путь, который обязан
работать на прозе ЛЮБОГО формата (список, абзац, таблица, любая
дисциплина), — `requirement_llm_extract.py` (ЛЛМ-вызов вместо шаблона).
`requirement_cross_check.py` принимает `list[Requirement]` от ЛЮБОГО
источника — сверка от формата извлечения не зависит.

Обобщает разовый ручной разбор пояснительной записки (список систем
противодымной защиты) в переиспользуемый модуль:
экстрактор «требование → список помещений» из свободного текста, а не
только из табличных реестров (rooms.py разбирает Экспликацию,
equipment.py — Ведомость оборудования; обе — таблицы. Здесь — проза).

Мотивация (сформулирована пользователем): человек при сверке ПД↔РД
сначала кратко выписывает из ПД, что где требуется (сводка требований и
параметров), а потом идёт по РД и проверяет каждый пункт. Один из уже
найденных на этом проекте примеров (нарушение №2, тёплые полы) устроен
именно так: требование записано в прозе ПЗ и НЕ имеет кода системы —
ни rooms.py (нет в таблице Экспликации), ни equipment.py (нет в
Ведомости), ни routing_graph.py (нет ветки на чертеже, само требование
не про трассировку) в принципе не могут его увидеть. Прямое измерение на
реальном томе проектной документации (см. тесты)
показало ДВА разных реальных вида предложений:

  1. Список с кодом системы (тире-пункт, законченный «;»):
     "- из поэтажных коридоров, пом. 108, 201 (ВД1);"
     Описание, запятая, один или несколько «пом. N, N» внутри пункта,
     код в скобках непосредственно перед «;». `extract_coded_requirements`.

  2. Требование без кода, список помещений в скобках ВНУТРИ предложения,
     где-то в этом же предложении — глагол-предикат «предусмотрен(о/а)»/
     «предусматривается» (оба вида глагола — совершенный и несовершенный,
     разные корни «предусмотр-»/«предусматр-», подтверждено на реальном
     тексте):
     "В помещениях ... (пом. 267, 270, 271, 272) предусмотрена система
     подогрева полов ...". `extract_predicate_requirements`.

Форма 2 — источник именно того нарушения, которое мотивировало этот
модуль, поэтому регулярка предиката НАМЕРЕННО узкая (только «предусм[оа]тр-»,
а не любой глагол): на том же файле есть похожие по форме, но НЕ
требования предложения — «... (пом. 007). В помещении ИТП устанавливается
...» (это указание места объекта, не отдельное требование к помещению) и
табличные подписи легенды («Наименование зоны обслуживания
(пом. 167)», без глагола вообще). Обе НЕ проходят фильтр предиката — это
проверено на реальном тексте, а не предположение (Г.11).

Границы поиска предложения — окно от предыдущего «. » до следующего
«. »/«!»/«?» вокруг совпадения «(пом. ...)», а не разбиение всего текста
на предложения заранее: «пом.» — само сокращение с точкой, наивный
разбор по «. следующая заглавная» ошибочно обрывает предложение прямо
после «пом.» перед номером (заглавная буква не при чём — там дальше
цифра, но лукбихайнд под «предыдущая точка = конец предложения» всё
равно ложно сработал бы на этом «.» — проверено и исправлено этим же
модулем: оконный поиск от «(пом.» назад/вперёд к ближайшим «. »
обходит проблему, не пытаясь построить универсальный сегментатор
предложений).
"""
from __future__ import annotations

import re
from collections.abc import Callable
from dataclasses import dataclass, field

_CODE_ITEM_RE = re.compile(
    r"(?:\n|^)[ \t]*[-–—]\s*"
    r"(?P<body>(?:(?!\n[ \t]*[-–—]).)+?)"
    r"\((?P<code>[А-ЯЁ]{1,5}\d+(?:\.\d+)?)\)\s*;",
    re.S,
)
_POM_RUN_RE = re.compile(r"пом\.\s*((?:\d+[,\s]*)+)")
_ROOM_PAREN_RE = re.compile(r"\(пом\.\s*(?P<rooms>[\d,\s]+)\)")
_PREDICATE_RE = re.compile(r"предусм[оа]тр\w*")
_SENT_BOUNDARY_RE = re.compile(r"[.!?]\s")

# Форма 3 (Г.47): глагольные корни нормативных предложений В ЦЕЛОМ по
# русскоязычной проектной/нормативной прозе — не подобраны под один
# документ (в отличие от узкого «предусм[оа]тр-» формы 2, см. докстринг
# ниже), это стандартные обязывающие конструкции («должен быть», «следует
# выполнять», «требуется», «устанавливается», «обеспечивается»,
# «выполняется из/по ГОСТ»), которыми пишут ЛЮБЫЕ разделы ПД, не только ОВ.
# Корень «выполн\w*» (не «выполня\w*») — реальный пропуск (Г.56): «выполня-»
# ловит только несовершенный вид («выполняется»), а совершенный
# («выполнить», «выполнены», «выполнена») — обычная форма технического
# требования («... выполнить из коррозионностойких материалов») — мимо не
# проходил вовсе. Найдено на реальном ПЗ: требование о материале
# изделия для группы помещений не извлекалось молча из-за одного символа.
# извлекалось молча из-за этого одного символа.
_GENERAL_PREDICATE_RE = re.compile(
    r"предусм[оа]тр\w*|должн\w*|необходимо\w*|следует\b|требуется\b|"
    r"устанавлива\w*|обеспечива\w*|выполн\w*",
    re.IGNORECASE,
)
# Граница предложения формы 3 — та же проблема, что докстринг модуля уже
# описал для формы 2 («пом.» — само сокращение с точкой): наивное
# разбиение по «X. » рвёт «(пом. 267, ...)» надвое и уносит номера
# помещений в другое «предложение», чем глагол-предикат (проверено на
# реальном тексте — без исключения `_rooms_in` находил 0 номеров там, где
# они явно есть). Отрицательный лукбихайнд на «пом» перед точкой — тот же
# компромисс адресно, без попытки построить общий сегментатор аббревиатур.
_GENERAL_SENT_BOUNDARY_RE = re.compile(r"(?:(?<!пом)\.|[!?])\s", re.IGNORECASE)


def _rooms_in(body: str) -> list[str]:
    rooms: list[str] = []
    for m in _POM_RUN_RE.finditer(body):
        for tok in re.findall(r"\d+", m.group(1)):
            if tok not in rooms:
                rooms.append(tok)
    return rooms


@dataclass
class Requirement:
    """Одно извлечённое из прозы ПД требование или способ производства работ.

    Г.86 — прямое требование пользователя: «требования должны быть уже
    привязаны к разделам... чтобы инспектор просто увидел результат, на
    какой странице требование». Отсюда `document`/`section`: без них при
    нескольких файлах в одном прогоне номера страниц конфликтуют (каждый
    файл начинает счёт с единицы), и понять, из какого тома требование,
    нельзя вообще — реальный пробел, найденный при перестройке (`page` без
    имени файла бессмысленен на комплекте из нескольких томов).

    `rooms` — номера помещений, если требование к ним привязано; ПУСТОЙ
    список означает «требование к объекту/системе целиком», а не «данных
    нет». Пустой список — нормальный, частый случай: на разделах ООС/ПОС/ПБ
    требования по своей природе относятся к объекту, а не к помещению N.
    """
    rooms: list[str]
    page: int
    sentence: str            # дословная цитата — ДОКАЗАТЕЛЬСТВО, не сводка
    code: str | None = None  # код системы (ВД1, ПД22, ...), если есть
    document: str = ""       # имя файла-источника (Г.86)
    section: str | None = None  # код раздела: ООС, АР, КР... (Г.86)
    # Г.93 — короткая суть требования, то, что инспектор читает в сводке.
    # Раньше модель её возвращала, а разбор ответа выбрасывал, и в сводку
    # шла цитата: получалась не выжимка, а переписанный документ. Пусто у
    # regex-пути — он коротких формулировок не делает вовсе, и тогда
    # показывается цитата: показать длинное лучше, чем не показать ничего.
    summary: str = ""
    # Г.101 — норматив из ПЕРЕЧНЯ ЭТОГО ТОМА, к которому относится требование.
    # Пусто — «не привязано», а не «норматива нет»: марки изделий и состав
    # работ часто не соответствуют нормативу перечня напрямую.
    norm: str = ""
    # Как получена привязка: «названа в требовании» (проверка подстрокой,
    # ошибиться не может) или «сопоставлено по смыслу» (гипотеза модели).
    # Слить их в одну пометку значило бы выдать предположение за факт.
    norm_source: str = ""
    # Г.106 — помещения, угаданные по НАЗВАНИЮ (экспликация того же тома), а
    # не названные номером в тексте. Отдельное поле, а не дописывание в
    # `rooms`: номер в скобках — факт, совпадение по названию — подсказка, и
    # смешать их значило бы выдать догадку за данные документа.
    rooms_by_name: list[str] = field(default_factory=list)


def extract_coded_requirements(text_facts: list[dict]) -> list[Requirement]:
    """Форма 1: тире-пункт «..., пом. N, N (КОД);». Возвращает по записи
    на каждый пункт списка, где нашёлся хотя бы один номер помещения."""
    out: list[Requirement] = []
    for fact in text_facts:
        text = fact["text"]
        for m in _CODE_ITEM_RE.finditer(text):
            rooms = _rooms_in(m.group("body"))
            if not rooms:
                continue
            sentence = " ".join(m.group(0).split())
            out.append(Requirement(
                rooms=rooms, page=fact["page"], sentence=sentence,
                code=m.group("code"),
            ))
    return out


def extract_predicate_requirements(text_facts: list[dict]) -> list[Requirement]:
    """Форма 2: «(пом. N, N) ... предусмотрен(о/а)/предусматривается ...»,
    без кода системы. Окно предложения — от предыдущего «. » до следующего
    «. »/«!»/«?», без предположения о разбиении всего текста заранее."""
    out: list[Requirement] = []
    for fact in text_facts:
        text = fact["text"]
        for m in _ROOM_PAREN_RE.finditer(text):
            start = text.rfind(". ", 0, m.start())
            start = start + 2 if start != -1 else 0
            end_m = _SENT_BOUNDARY_RE.search(text, m.end())
            end = end_m.end() if end_m else len(text)
            sentence = " ".join(text[start:end].split())
            if not _PREDICATE_RE.search(sentence):
                continue
            rooms = sorted(set(re.findall(r"\d+", m.group("rooms"))))
            if not rooms:
                continue
            out.append(Requirement(rooms=rooms, page=fact["page"], sentence=sentence))
    return out


def extract_requirements(text_facts: list[dict]) -> list[Requirement]:
    """Обе формы вместе — полный реестр требований из прозы ПД."""
    return extract_coded_requirements(text_facts) + extract_predicate_requirements(text_facts)


def _split_sentences(text: str) -> list[str]:
    """Делит текст на предложения по `_GENERAL_SENT_BOUNDARY_RE` — здесь,
    в отличие от формы 2 (окно вокруг конкретного якоря), нужны ВСЕ
    предложения сразу, поэтому разбиение идёт заранее по всему тексту."""
    sentences: list[str] = []
    start = 0
    for m in _GENERAL_SENT_BOUNDARY_RE.finditer(text):
        sentences.append(text[start:m.end()])
        start = m.end()
    if start < len(text):
        sentences.append(text[start:])
    return sentences


def extract_general_requirements(
    text_facts: list[dict], min_len: int = 20, max_len: int = 500,
) -> list[Requirement]:
    """Форма 3 (Г.47) — каталог требований из прозы ШИРЕ, чем форма 2: не
    требует «(пом. N)» рядом и не ограничен корнем «предусмотр-/предусматр-».

    Реальное измерение на томе пояснительной записки (177 страниц): форма 2
    нашла 2 требования без кода за весь документ — а сотня с лишним
    нормативных предложений вида «снабжение системы предусматривается
    от такого-то узла», «все применяемые приборы должны быть выполнены в
    таком-то исполнении», «изделие выполняется из такого-то материала по
    ГОСТ», «самостоятельные системы предусмотрены для перечня зон» —
    остались НЕВИДИМЫ прежней сводке —
    не потому что их там нет, а потому что рядом не было буквального
    «(пом. N)». Инспектору, открывающему ПД впервые, нужен полный каталог
    того, что там вообще написано, а не только то, что попало в один
    наблюдённый на нарушении №2 паттерн.

    `rooms` — номера, если рядом есть «пом. N» (в любой форме, не только
    скобочной — переиспользует `_rooms_in`); ПУСТОЙ список, если требование
    не привязано к конкретному помещению (значит «общее» требование к
    объекту/системе/зоне, а не «требование ко всем помещениям сразу») —
    `render_requirements_summary` уже печатает такие как «не указаны».

    Это КАТАЛОГ ДЛЯ ЧЕЛОВЕКА, не вход в автоматическую сверку по номеру
    помещения: `extract_requirements()` (сверка/эскалация/триангуляция,
    Г.33/Г.46) эту форму НЕ включает — широкий охват по конструкции идёт
    в обмен на точность (описательное предложение с тем же глагольным
    корнем пройдёт фильтр наравне с настоящим требованием), а
    `requirement_cross_check.py`/`triangulation.py` рассчитаны на
    прицельные, а не шумные сигналы (тот же принцип, что Г.42 уже
    сформулировал для другого места пайплайна). Здесь шум — приемлемая
    цена за полноту того, что видит человек, а не автоматика."""
    out: list[Requirement] = []
    for fact in text_facts:
        for raw in _split_sentences(fact["text"]):
            sentence = " ".join(raw.split())
            if not (min_len <= len(sentence) <= max_len):
                continue
            if not _GENERAL_PREDICATE_RE.search(sentence):
                continue
            rooms = _rooms_in(sentence)
            out.append(Requirement(rooms=rooms, page=fact["page"], sentence=sentence))
    return out


# Г.57: у требования формы 3 номеров помещений в скобках нет вообще (иначе
# это форма 2) — но само предложение часто называет ТИП помещения словами
# («лаборанских», «кабинетах физики и химии»), которые пересекаются со
# словами в НАЗВАНИИ конкретных помещений реестра («Физического
# эксперимента», «Лаборантская тип АВ»). Реальный случай: единственная
# текстовая зацепка для помещений 140/141/147/198 в разобранном ПД — именно
# такое предложение, без единого номера рядом.
#
# Порог общего префикса — 4 буквы, не больше (проверено на реальных парах):
# «химического»/«химии» расходятся уже на 5-й букве («хими[ч]» vs
# «хими[и]»), «физического»/«физики» — на 5-й тоже. Более жёсткий порог не
# нашёл бы эту самую пару, ради которой правило и заводится. Шум от такого
# короткого порога сдерживается требованием длины ≥5 у ОБОИХ слов и тем,
# что это информационная привязка «похоже относится к», не автовывод —
# решает инспектор, не сверка.
_ROOM_KEYWORD_MIN_WORD_LEN = 5
_ROOM_KEYWORD_MIN_PREFIX = 4

def _significant_words(text: str) -> set[str]:
    words = re.findall(r"[а-яё]+", text.lower())
    return {w for w in words if len(w) >= _ROOM_KEYWORD_MIN_WORD_LEN}


# Г.108 — почему здесь НЕТ отсева и НЕТ ни одного порога.
#
# Слово, которым назван предмет тома, стоит почти в каждом его требовании и
# потому плохо указывает на место. Отделить его от слова, называющего место,
# пробовали четырьмя способами: доля требований с этим словом, доля названий
# помещений, число разных слов-соседей в названиях, двусторонний idf. Ни один
# не дал границы, которая не была бы подогнана под разобранные документы, и
# это ожидаемо: одно и то же слово бывает И темой тома, И названием типа
# помещения одновременно — разделения нет в самих данных.
#
# Поэтому подсказка ничего не выбрасывает: она РАНЖИРУЕТ. Помещение, чьё
# название совпало по редкому слову, стоит выше помещения, совпавшего по
# слову, которое встречается повсюду. Сколько взять из этого порядка, решает
# бюджет потребителя (сколько листов инспектор успеет посмотреть), а не
# придуманный порог истины. Вес слова — вычисляемая величина, а не число в
# коде: чем в большем числе названий и томов слово встречается, тем меньше
# оно различает.
def match_requirement_rooms_by_name(sentence: str, room_facts: list[dict],
                                    word_weight: Callable[[str], float] | None = None
                                    ) -> list[str]:
    """Помещения, чьё НАЗВАНИЕ пересекается по ключевому слову с текстом
    требования — не строгая привязка (в отличие от `rooms`, где номер стоит
    в документе явно), а подсказка «вероятно, речь об этих помещениях».

    Возвращает номера ПО УБЫВАНИЮ различительной силы совпавшего слова:
    ничего не отсеивается, порядок и есть ответ (см. заметку выше). Без
    `word_weight` все слова равны, и порядок остаётся реестровым — механизм
    работает и когда взвешивать нечем.
    """
    req_words = _significant_words(sentence)
    if not req_words:
        return []
    scored: list[tuple[float, int, str]] = []
    seen: set[str] = set()
    for position, fact in enumerate(room_facts):
        key = fact.get("key")
        if not key or key in seen:
            continue
        best = 0.0
        for room_word in _significant_words(fact.get("name") or ""):
            for req_word in req_words:
                if room_word[:_ROOM_KEYWORD_MIN_PREFIX] != req_word[:_ROOM_KEYWORD_MIN_PREFIX]:
                    continue
                weight = word_weight(room_word) if word_weight else 1.0
                best = max(best, weight)
        if best > 0:
            seen.add(key)
            scored.append((best, position, key))
    # При равном весе порядок остаётся прежним — по первому появлению в
    # реестре: устойчивость важнее, чем красота сортировки.
    scored.sort(key=lambda item: (-item[0], item[1]))
    return [key for _, _, key in scored]


# Г.67 — реальная жалоба на «воду» в форме 3: одна и та же шаблонная фраза
# (типовая оговорка/ссылка на норму) буквально повторяется на разных
# страницах/томах одного комплекта, и раньше печаталась в каталоге
# отдельной строкой на каждое совпадение. Дедупликация по нормализованному
# тексту предложения (без переноса самой Requirement-модели и без влияния
# на `requirement_cross_check.py`, который форму 3 потребляет поштучно —
# см. докстринг модуля) — только на уровне печатного отчёта для человека.
def _normalize_for_dedup(sentence: str) -> str:
    return " ".join(sentence.split()).lower()


# Мягкая эвристика (НЕ фильтр, только визуальная пометка, Г.10 — ничего не
# прячется): предложение, которое ЦЕЛИКОМ состоит из «сделать X в
# соответствии с/согласно ГОСТ/СП/СНиП...» и не несёт другого технического
# содержания — самый частый источник «воды» в каталоге после самого факта
# дублей. Реальный пример с разобранного тома: «Работы выполнять в
# соответствии с действующими <два обозначения нормативов>.» — около 70
# символов, никакой информации сверх самой ссылки. Признак заведомо
# неполный (не поймает все такие предложения и может пометить не только
# их) — честно эвристика, не точный классификатор.
_NORM_ONLY_RE = re.compile(
    r"^.{0,40}?(?:в\s+соответствии\s+со?|согласно|по)\s+(?:\S+\s+){0,3}"
    r"(?:ГОСТ|СП|СНиП|СанПиН|ПУЭ)[\w\s\d.,\-/]*\.?$",
    re.IGNORECASE,
)


def _is_norm_reference_only(sentence: str) -> bool:
    return bool(_NORM_ONLY_RE.match(sentence))


def render_general_requirements_summary(requirements: list[Requirement]) -> str:
    """Печатный каталог формы 3 (Г.47) — отдельно от `render_requirements_summary`
    (формы 1+2), с явной оговоркой в заголовке, что это НЕ вход в автосверку.

    Г.67: одинаковые по тексту требования с разных страниц печатаются ОДНОЙ
    строкой (список всех страниц, где встретились), а не по одной записи на
    каждое совпадение — раньше именно это было основным источником «воды» в
    каталоге. Предложения, которые выглядят как голая ссылка на норму без
    другого содержания, помечаются `[только ссылка на норму]` — это только
    видимая пометка, не удаление (Г.10)."""
    groups: dict[str, list[Requirement]] = {}
    order: list[str] = []
    for req in requirements:
        key = _normalize_for_dedup(req.sentence)
        if key not in groups:
            groups[key] = []
            order.append(key)
        groups[key].append(req)
    dedup_note = f" (уникальных формулировок: {len(order)})" if len(order) != len(requirements) else ""
    lines = [
        f"=== Общие требования ПД (Г.47, без привязки к конкретному "
        f"помещению — для просмотра, не для автосверки) — извлечено: "
        f"{len(requirements)}{dedup_note} ===",
    ]
    for i, key in enumerate(order, 1):
        group = groups[key]
        first = group[0]
        pages = sorted({r.page for r in group})
        pages_str = ", ".join(str(p) for p in pages)
        rooms = sorted({room for r in group for room in r.rooms}, key=lambda x: (len(x), x))
        rooms_part = f" — помещения: {', '.join(rooms)}" if rooms else ""
        dup_part = f" (повторено {len(group)}×)" if len(group) > 1 else ""
        tag = " [только ссылка на норму]" if _is_norm_reference_only(first.sentence) else ""
        lines.append(f"{i}. стр.{pages_str}{rooms_part}{dup_part}{tag}")
        lines.append(f"   «{first.sentence}»")
    return "\n".join(lines)


def render_requirements_summary(requirements: list[Requirement]) -> str:
    """«Сводка требований ПД» — печатный список того, что извлечено из
    прозы ПД, ДО всякой сверки с РД. Существует не только для контроля
    (проверить, что извлечение вообще что-то нашло), но и как отдельный
    артефакт: то, что человек делает вручную при сверке ПД↔РД (сначала
    выписать, что где требуется — см. докстринг модуля выше), теперь можно
    прочитать напрямую, не запуская весь конвейер заново и не держа список
    в контексте разговора."""
    lines = [f"=== Сводка требований ПД (Г.32) — извлечено: {len(requirements)} ==="]
    for i, req in enumerate(requirements, 1):
        code = f" [{req.code}]" if req.code else ""
        rooms = ", ".join(req.rooms) if req.rooms else "не указаны"
        lines.append(f"{i}. стр.{req.page}{code} — помещения: {rooms}")
        lines.append(f"   «{req.sentence}»")
    return "\n".join(lines)
