"""Позиции ведомости оборудования (Приложение Г.20) — тот же реестровый
паттерн, что и `rooms.py` для помещений, только ключ другой: код позиции
спецификации, часто иерархический («14» — установка, «14.1»/«14.2» — её
комплектующие).

Формат таблицы «плывёт» от раздела к разделу и от автора к другому (Г.21:
риск непереноса на другой комплект оценён как высокий, статус n=1) — в
отличие от `rooms.py`, где номер помещения всегда трёхзначный и название
всегда с кириллицы. Здесь позиция может начинаться с двух-трёхзначного кода,
а название — с чего угодно (маркировка оборудования часто начинается с
латиницы или цифры: «ВЦ4-75», «1ВО-06»), поэтому отсев ложных срабатываний
строже завязан на структуру строки (код → название → количество), а не на
словарные признаки конкретного названия.
"""
from __future__ import annotations

import re

# Код позиции: 1–3 цифры, необязательный дочерний индекс через точку (тоже
# 1–2 цифры) — «14», «14.1», «102.2». Без буквенного варианта: в отличие от
# номеров помещений, литерные позиции оборудования на исходном комплекте не
# наблюдались (Г.11 — не вводить признак без наблюдения).
_POS_RE = re.compile(r"^(\d{1,3}(?:\.\d{1,2})?)$")
_QTY_RE = re.compile(r"^(\d+)\s*(?:шт\.?|компл\.?)?$", re.I)
# Строки, которые никогда не бывают названием оборудования: заголовки
# столбцов таблицы спецификации.
_HEADER_RE = re.compile(
    r"^(поз\.?|обозначение|наименование|кол-?во|количество|примечание|"
    r"марка|тип|позиция)\.?$", re.I)

_MAX_NAME_LINES = 2

# Реальный шум слепого прогона по всему комплекту (Г.29/Г.30, п.0): классы
# строк, которые по форме неотличимы от «код / название» ведомости, но
# названием оборудования не являются — каждый заведён по конкретному
# наблюдённому ложному срабатыванию (Г.11), не «на всякий случай».
_REJECT_NAME_RE = re.compile(
    r"^(?:"
    # Поле подписи штампа: дата в форме «\d{1,2}.\d{1,2}» (месяц.год —
    # «01.23») читается регексом кода позиции как родитель.дочерний, а
    # следующая строка — не название, а подпись/должность из штампа.
    r"ГИП|Разраб\.?|Н\.?\s*контр\.?|Проверил|Утвердил|Согласовано|"
    r"Изм\.?\s*внес|Составил|Изм\.?\s*Кол\.?|"
    # Заголовок листа из «Содержания»/«Ведомости чертежей»: номер листа
    # рядом с его названием по форме совпадает с «код / название» ведомости
    # оборудования, но это название ЛИСТА.
    r"Принципиальная\s+схема|План\b|Разрез\b|Экспликация|Ведомость|"
    r"Содержание|Графические\s+материалы|Спецификация|Таблица|"
    # Шифр документа, повторяющийся в подвале каждой страницы ведомости
    # (форма «XXX/000000/1-П-ВОР.ИОС5.4.2 Формат: А3») — код+пробел+текст
    # совпадает с «код / название», но это не позиция, а колонтитул.
    r"[А-Я]{2,5}/\d+/\d+-|"
    # Нормативная ссылка, случайно подхваченная как «название» позиции.
    r"ГОСТ\b|СП\s?\d|СНиП\b|"
    # Нумерованный пункт пояснительной записки («7. Обоснование...», иногда
    # с предшествующим тире переноса строки «- 16. Обоснование...») —
    # начинается с номера пункта и точки с пробелом, что для названия
    # оборудования не встречается.
    r"-?\s*\d{1,2}\.\s|"
    # Отметка уровня (штамп сечения/разреза, «-2.950», «+3.600») с
    # необязательным пределом огнестойкости рядом («EI30», «EI 30», «EIW-30»)
    # — реальный шум слепого прогона (Г.29): код позиции по форме совпал с
    # номером помещения на схеме, а следующая строка — отметка высоты или
    # маркировка огнестойкости с соседнего разреза, не название оборудования.
    r"[-+]?\d{1,3}[.,]\d{3}\b|EIW?[\s-]?\d{2,3}\b|"
    # Наименование организации (застройщик/подрядчик из штампа) — форма
    # совпадает с «код / название», но это не оборудование, а колонтитул
    # штампа («08.24 ООО <наименование> Лист Листов»).
    r"(?:ООО|АО|ЗАО|ОАО|ПАО|ИП)\b|"
    # Заголовок «Состав рабочей/проектной документации» (Г.17) — тот же
    # колонтитульный шум, что «Ведомость»/«Содержание» выше, отдельная
    # формулировка на реальном комплекте.
    r"Состав\s+\S+\s+документации"
    r")", re.I)
_BARE_UNIT_NAME_RE = re.compile(r"^(?:шт|компл|м|м2|м3|кг|компл\.?)\.?$", re.I)
# Строка-заполнитель таблицы («-», «-//-», «-//- -//-») — не название.
_FILLER_NAME_RE = re.compile(r"^[-/.\s]+$")


def _parent_key(key: str) -> str | None:
    """«14.1» → «14»; «14» → None (уже родитель)."""
    if "." in key:
        return key.split(".", 1)[0]
    return None


def extract_equipment_facts(text: str, room_keys: set[str] | None = None) -> list[dict]:
    """Возвращает [{key, name, parent?, qty?}] — позиции ведомости
    оборудования, найденные на листе.

    Как и в rooms.py: PyMuPDF почти всегда разносит код, название и
    количество по отдельным строкам, поэтому запись сначала схлопывается.

    `room_keys` — номера помещений, уже найденные на ЭТОЙ ЖЕ странице
    `rooms.extract_room_facts`. Регекс кода позиции и регекс номера
    помещения оба принимают короткие числа с тем же диапазоном длины — на
    реальном прогоне (первая слепая проверка Г.20) подавляющее большинство
    "позиций оборудования" оказались повторно разобранными номерами
    помещений с той же страницы (экспликация, шапка штампа). Номер
    помещения на странице приоритетнее: если ключ уже занят помещением, это
    не позиция ведомости."""
    lines = [ln.strip() for ln in text.splitlines()]
    facts: list[dict] = []
    i, n = 0, len(lines)
    while i < n:
        line = lines[i]
        if not line:
            i += 1
            continue

        m_pos = _POS_RE.match(line)
        if m_pos:
            key = m_pos.group(1)
            j = i + 1
            name_parts: list[str] = []
            qty: str | None = None
            while j < n and len(name_parts) < _MAX_NAME_LINES:
                frag = lines[j].strip()
                if not frag:
                    j += 1
                    continue
                m_qty = _QTY_RE.match(frag)
                if m_qty and name_parts:
                    # Голое число сразу после названия — это количество, а
                    # не следующая позиция: у обеих одинаковый вид «\d+»,
                    # поэтому количество проверяется раньше разрыва записи.
                    qty = m_qty.group(1)
                    j += 1
                    break  # количество — конец текущей записи
                if _POS_RE.match(frag):
                    break  # следующая позиция началась
                if _HEADER_RE.match(frag):
                    j += 1
                    continue  # заголовок столбца затесался между строк
                name_parts.append(frag)
                j += 1
            name = " ".join(name_parts).strip()
            is_noise = (_HEADER_RE.match(name) or _REJECT_NAME_RE.match(name)
                        or _BARE_UNIT_NAME_RE.match(name) or _FILLER_NAME_RE.match(name)
                        or "=" in name)
            if name and not is_noise and not (room_keys and key in room_keys):
                fact = {"key": key, "name": name}
                parent = _parent_key(key)
                if parent:
                    fact["parent"] = parent
                if qty:
                    fact["qty"] = qty
                facts.append(fact)
            i = j
            continue

        i += 1

    return facts
