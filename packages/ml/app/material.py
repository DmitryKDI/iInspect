"""Отсев непроектного материала — прайсов и каталогов поставщика.

Замер на реальном томе рабочей документации: 427 из 576 текстовых страниц
оказались единой подборкой коммерческих предложений поставщика
оборудования на 419 страниц, подшитой внутрь тома (сквозная нумерация
«Страница N из M», номера предложений). Это не проектная документация:
сравнивать её с расчётной запиской ПД бессмысленно, а её числа (масса,
характеристики, цена) засоряют реестры и порождают ложные совпадения при
сопоставлении листов.

Материал не выбрасывается молча: причина возвращается наружу, чтобы лист
был виден пользователю как «вне сравнения», а не пропал беззвучно.
"""
from __future__ import annotations

import re
from typing import Optional

# Колонтитул многостраничного каталога. Порог знаменателя намеренно высокий:
# «Страница 2 из 5» — нормальная нумерация проектного документа, а
# «Страница 2 из 419» — признак подшитого каталога.
_CATALOG_PAGINATION = re.compile(r"Страниц[аы]\s+\d+\s+из\s+(\d{2,})", re.I)
_MIN_CATALOG_PAGES = 20

_COMMERCIAL = re.compile(
    r"коммерческое предложение|Предложение\s*№\s*\w|прайс[- ]лист|"
    r"Гарантийный\s+срок", re.I)

# Внутренняя страница того же подшитого каталога (Г.28), но без колонтитула
# «Страница N из M» и без маркерных фраз выше — реальный случай: страница
# сметы «Итого по <группа>» с построчными ценами («63 056,10», «Итого по
# К2» и т.п.), которая проскочила оба фильтра и (без текстового отсева)
# попадает в сравнение как обычный чертёж. Числа с копейками через запятую
# в таком количестве на странице — не характерны для проектной документации
# и её ведомостей (там количество/площадь, не цена), но типичны для сметы
# поставщика.
_PRICE_TOKEN = re.compile(r"\d{1,3}(?: \d{3})*,\d{2}")
_MIN_PRICE_TOKENS = 6
_SUBTOTAL = re.compile(r"Итого\s+по\b", re.I)


def non_project_reason(text: str) -> Optional[str]:
    """Причина, по которой лист не является проектным материалом, или None."""
    m = _CATALOG_PAGINATION.search(text)
    if m and int(m.group(1)) >= _MIN_CATALOG_PAGES:
        return f"каталог поставщика (страница из {m.group(1)})"
    if _COMMERCIAL.search(text):
        return "коммерческое предложение поставщика"
    if _SUBTOTAL.search(text) and len(_PRICE_TOKEN.findall(text)) >= _MIN_PRICE_TOKENS:
        return "ценовая таблица сметы поставщика (без колонтитула страницы)"
    return None
