"""Код обязан быть общим для любой проектной документации.

Автоматическая проверка не допускает реквизиты конкретного объекта,
предметные константы в механике и комментарии, привязанные к одному разделу.

## Что именно запрещено и почему

**Реквизиты проверяемого объекта** — шифр, наименование организации, имя тома.
Они не делают код менее общим сами по себе, но раскрывают данные объекта и
могут непреднамеренно повлиять на проверку.

**Конкретные обозначения нормативов** в механике. Норматив — это НАБЛЮДЕНИЕ о
разделе («в вентиляции применяется такой-то СП»), а наблюдения живут в
реестре данных, а не в коде и не в комментарии. Комментарий с
примером из одного тома задаёт рамку следующему читателю не слабее кода, а
попав в промпт — якорит модель на чужом документе.

## Два законных исключения, оба объявлены явно

`_DATA_REGISTRIES` — файлы, которые ПО СВОЕМУ НАЗНАЧЕНИЮ являются реестрами
наблюдений: подключение нового раздела к ним и есть штатный способ расширения.
Добавление файла в этот список — осознанное решение, а не побочный
эффект правки.

`_DOCUMENT_FORM_STANDARDS` — стандарты, задающие ФОРМУ документации, а не
содержание раздела: основная надпись, состав и обозначения комплектов. Они
применимы к любому разделу по определению, поэтому механика на них ссылаться
обязана — иначе пришлось бы объяснять форму штампа, не называя стандарт,
который её задаёт.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

ROOT = Path(__file__).resolve().parents[3]
APP = Path(__file__).resolve().parents[1] / "app"
SCRIPTS = ROOT / "scripts"

# Публичная документация должна описывать общий продукт, а не один пример.
_PUBLIC_DOC_FILES = ("README.md", "docs/СТРУКТУРА-ПРОГРАММЫ.md", "docs/ПРИЁМКА.md")

# Лексика ОДНОГО раздела проектной документации. В инструкции правило,
# сформулированное такими словами, читается как правило про этот раздел —
# даже если механизм общий. Список заведомо неполный и это нормально: он
# ловит самый частый случай, а не заменяет чтение (Г.11).
# Г.107 — та же лексика, но разложенная по дисциплинам, для проверки КОДА.
# Перечисление слов из НЕСКОЛЬКИХ дисциплин — не заточка, а ровно наоборот:
# так объясняют, что механизм общий («ответвление трассы, стояк, групповая
# линия щита — одно и то же наблюдение»). Заточка — когда весь файл говорит
# словами ОДНОЙ дисциплины: тогда и читатель, и модель принимают частный
# случай за правило. Поэтому файл виноват не в наличии слов, а в том, что
# все они из одной группы.
_DISCIPLINE_WORD_GROUPS = {
    "климат": r"воздухообмен\w*|воздуховод\w*|венткамер\w*|дымоудален\w*|радиатор\w*|"
              r"теплоноситель\w*|приточн\w*|вытяжн\w*|отоплени\w*|вентиляц\w*|"
              r"кондиционир\w*|подпор\w*|отсос\w*",
    "вода": r"канализац\w*|водоснабжен\w*|водоотведен\w*|водопровод\w*|стояк\w*|сантехн\w*",
    "конструкции": r"бетон\w*|арматур\w*|железобетон\w*|каркас\w*|фундамент\w*",
    "электрика": r"кабел\w*|электрощит\w*|электрическ\w*|светильник\w*|розетк\w*|щит\w*",
}
_GROUP_RES = {g: re.compile(rf"\b(?:{p})\b", re.IGNORECASE)
              for g, p in _DISCIPLINE_WORD_GROUPS.items()}


def _single_discipline_offence(path: "Path") -> str:
    """Пусто, если файл к одной дисциплине не привязан."""
    if path.name in _DATA_REGISTRIES:
        return ""
    src = path.read_text(encoding="utf-8")
    used = {g: [src[: m.start()].count("\n") + 1 for m in r.finditer(src)]
            for g, r in _GROUP_RES.items()}
    used = {g: lines for g, lines in used.items() if lines}
    if len(used) != 1:
        return ""
    group, lines = next(iter(used.items()))
    where = ", ".join(f"стр.{n}" for n in lines[:6])
    return f"{path.name}: лексика только одной дисциплины ({group}): {where}"


_ONE_DISCIPLINE_VOCABULARY = re.compile(
    r"\b(?:воздухообмен\w*|воздуховод\w*|венткамер\w*|дымоудален\w*|радиатор\w*|"
    r"теплоноситель\w*|стояк\w*|приточн\w*|вытяжн\w*|отоплени\w*|вентиляц\w*|"
    r"кондиционир\w*|подпор\w*|бетон\w*|арматур\w*|канализац\w*|водоснабжен\w*)\b",
    re.IGNORECASE)

# Файлы-реестры: наблюдения о разделах — их прямое содержимое (Г.88).
_DATA_REGISTRIES = {
    "table_registry.py",    # типы таблиц по разделам, у каждого свой термин
    "subsystem.py",         # лексика подсистем по разделам
    "set_overview.py",      # марки комплектов и их официальные названия
}

# Стандарты формы документации: применимы к любому разделу по определению.
_DOCUMENT_FORM_STANDARDS = (
    r"ГОСТ\s+Р\s+21\.1101",   # основная надпись, общие требования к ПД и РД
    r"ГОСТ\s+Р\s+21\.101",    # то же, действующая редакция
    r"ГОСТ\s+21\.101",         # то же, прежнее обозначение
    r"ГОСТ\s+2\.301",          # ЕСКД: форматы листов любого чертежа
    r"ГОСТ\s+2\.307",          # ЕСКД: нанесение размеров на любом чертеже
)

_NORM = re.compile(
    r"\b(?:СП|СНиП|ГОСТ\s+Р|ГОСТ|СанПиН|СанПин|НПБ|ВСН|МДС)\s+[0-9Р][0-9.\-–*/]*")
_FORM_STANDARD = re.compile("|".join(_DOCUMENT_FORM_STANDARDS))

# Реквизиты проверяемого объекта. Шаблоны, а не литералы: перечислить сами
# реквизиты в тесте значило бы внести их в репозиторий, чего запрещает Г.12.
_OBJECT_MARKERS = {
    "шифр проекта": re.compile(r"([А-ЯA-Z]{2,})\s*/\s*(\d{4,})\s*/\s*\d"),
    "наименование организации": re.compile(r"\b(?:ООО|АО|ЗАО|ОАО|ПАО|ИП)\s*«[^»]{2,60}»"),
    # Маркировка конкретного тома: три и более двузначных группы через дефис.
    # Не «Том 5.4.2» сам по себе — номер тома по ПП №87 это форма, а не
    # реквизит; реквизит — маркировка файла с ней рядом.
    "маркировка тома": re.compile(r"(?<!\d)\d{2}-\d{2}-\d{2}(?:-\d{2})*(?!\d)"),
    # Три класса данных объекта, которые нельзя хранить в коде и комментариях.
    #
    # 1. Шифр комплекта целиком: «<буквы>-<цифры>-<..>-РД-<марка>». Форму
    #    объяснять можно и нужно, но обезличенным шаблоном (Г.89).
    "шифр комплекта": re.compile(
        r"\b[А-ЯA-Z]{2,}[-–]\d{3,}[-–][\dА-ЯA-Z.]+[-–](?:РД|ПД|ИД|П)[-–][А-ЯA-Z0-9.]+"),
    # 2. Имя файла тома: любое имя документа с кириллицей внутри — в
    #    механике его быть не может, пути приходят аргументом.
    # Роль-заглушка («ПД.pdf», «РД2.pdf») — не реквизит, а ровно то, чем
    # объясняют вызов: короткий стем из заглавных букв и необязательной
    # цифры. Реквизит — имя с настоящим шифром и хвостом версии.
    "имя файла тома": re.compile(
        r"""[^\s"'«»]*[А-Яа-яЁё][^\s"'«»]*\.(?i:pdf)"""),
    # 3. Кодовое имя объекта или набора: «Название-000» в кавычках либо
    #    ссылка на конкретный каталог документов. Проверка не знает самих
    #    имён (написать их сюда значило бы внести реквизит в репозиторий),
    #    поэтому ловит форму.
    # Кодовое имя объекта: «Название-000» — минимум одна кириллическая
    # буква, иначе сюда попадают обозначения по ГОСТ вида «EIW-30».
    # Каталог документов: имя, склеенное со словом sample через разделитель
    # («набор_sample»), а не любое слово с этой подстрокой — иначе ловится
    # атрибут `Pixmap.samples` стороннего пакета.
    "имя объекта или набора": re.compile(
        r"«[А-ЯЁA-Z][А-Яа-яЁёA-Za-z]*[А-Яа-яЁё][А-Яа-яЁёA-Za-z]*[-–]\d{2,}»"
        r"|\b\w+[_-][Ss]ample\w*\b|\b[Ss]ample[_-]\w+\b"),
}

# Обезличенный шаблон формы — не реквизит, а ровно то, что требует Г.89:
# объяснить форму шифра, не называя объект. Признак: буквы одинаковые (XXX)
# либо цифры нулевые (000000).
def _is_placeholder(match: "re.Match") -> bool:
    if match.re is _OBJECT_MARKERS["шифр проекта"]:
        letters, digits = match.group(1), match.group(2)
        return len(set(letters.upper())) == 1 or set(digits) == {"0"}
    if match.re is _OBJECT_MARKERS["имя файла тома"]:
        # Роль-заглушка в примере запуска («ПД.pdf», «путь/том2.pdf») — не
        # реквизит, а ровно то, чем объясняют вызов: одно короткое слово без
        # пробелов и разделителей. Реквизит — имя с шифром и хвостом версии.
        stem = re.split(r"[\\/]", match.group(0))[-1][: -len(".pdf")]
        return bool(re.fullmatch(r"[А-Яа-яЁёA-Za-z]{1,8}\d{0,2}", stem))
    return False


def _sources() -> list[Path]:
    files = sorted(APP.glob("*.py"))
    if SCRIPTS.is_dir():
        files += sorted(SCRIPTS.glob("*.py"))
    return files


def _offences(path: Path) -> list[str]:
    src = path.read_text(encoding="utf-8")
    out: list[str] = []
    for label, pattern in _OBJECT_MARKERS.items():
        for m in pattern.finditer(src):
            if _is_placeholder(m):
                continue
            line = src[: m.start()].count("\n") + 1
            out.append(f"{path.name}:{line} реквизит объекта ({label})")
    if path.name in _DATA_REGISTRIES:
        return out
    for m in _NORM.finditer(src):
        if _FORM_STANDARD.match(m.group(0)):
            continue
        line = src[: m.start()].count("\n") + 1
        out.append(f"{path.name}:{line} обозначение норматива в механике: {m.group(0)}")
    return out


def test_no_object_identifiers_and_no_norm_designations_in_mechanics():
    """Механика не должна знать ни проверяемый объект, ни конкретный норматив.

    Падение этого теста означает не «поправь строчку», а «наблюдение попало
    туда, где ему не место»: его надо либо обобщить до роли, либо перенести в
    реестр данных, либо (для реквизита объекта) убрать совсем.
    """
    offences = [o for path in _sources() for o in _offences(path)]
    assert not offences, (
        "Код и комментарии заточены под конкретный пример.\n"
        "Обобщите до роли, перенесите в реестр данных или уберите:\n  "
        + "\n  ".join(offences))


def test_the_check_actually_catches_what_it_claims():
    """Проверка, которую нельзя проверить, — это ещё одно правило на память.

    Тест самой проверки: подсунуть строку каждого запрещённого вида и
    убедиться, что она ловится, а разрешённые — нет.
    """
    import tempfile

    bad = [
        "# пример шифра ЖКХ/123456/7-РД-ОВ1 из реального комплекта",
        '# в штампе стоит ООО «Некая организация»',
        "# файл V0_00-05-04-02-07_Том 5.4.2 использован в примере",
        "# по СП 60.13330.2020 воздухообмен считается так",
    ]
    good = [
        "# основная надпись по ГОСТ Р 21.1101 — форма любого листа",
        "# шифр вида «XXX/000000/1-РД-<марка>» — обезличенный шаблон формы",
        "# номер тома по ПП №87 (Том 5.4.2) — форма обозначения, не реквизит",
        "# шифр вида «буквы/цифры/цифра-РД-марка», к разделу не привязан",
        '# наименование организации из штампа: ООО, АО, ЗАО — форма, не имя',
        '# заголовок версии API "api-version": "2023-06-01" — не маркировка тома',
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for i, line in enumerate(bad):
            p = Path(tmp) / f"bad_{i}.py"
            p.write_text(line, encoding="utf-8")
            assert _offences(p), f"не поймано: {line}"
        for i, line in enumerate(good):
            p = Path(tmp) / f"good_{i}.py"
            p.write_text(line, encoding="utf-8")
            assert not _offences(p), f"ложное срабатывание: {line} -> {_offences(p)}"


def _doc_offences(path: Path, forbid_vocabulary: bool) -> list[str]:
    src = path.read_text(encoding="utf-8")
    out: list[str] = []
    for label, pattern in _OBJECT_MARKERS.items():
        for m in pattern.finditer(src):
            if _is_placeholder(m):
                continue
            line = src[: m.start()].count("\n") + 1
            out.append(f"{path.name}:{line} реквизит объекта ({label})")
    if not forbid_vocabulary:
        return out
    for m in _NORM.finditer(src):
        if _FORM_STANDARD.match(m.group(0)) or m.group(0).startswith("ГОСТ Р 34.10"):
            continue
        line = src[: m.start()].count("\n") + 1
        out.append(f"{path.name}:{line} обозначение норматива: {m.group(0)}")
    for m in _ONE_DISCIPLINE_VOCABULARY.finditer(src):
        line = src[: m.start()].count("\n") + 1
        out.append(f"{path.name}:{line} лексика одного раздела: {m.group(0)}")
    return out


def test_public_docs_are_written_for_any_documentation_not_for_one_example():
    """Публичные документы не содержат реквизитов объекта или узких правил."""
    offences = [o for name in _PUBLIC_DOC_FILES
                for o in _doc_offences(ROOT / name, forbid_vocabulary=True)]
    assert not offences, (
        "Документация написана под конкретный пример.\n"
        "Сформулируйте правило через роль, а предметные наблюдения храните в данных:\n  "
        + "\n  ".join(offences))



def test_mechanics_do_not_speak_the_words_of_one_discipline():
    """В механике и порядке работы не должно быть акцента на отдельные тома.

    Проверка ищет отраслевую лексику в исполняемом коде и промптах: если весь
    файл говорит словами одной дисциплины, частный случай может стать правилом.

    Перечисление нескольких дисциплин намеренно РАЗРЕШЕНО: им объясняют, что
    наблюдение общее, и запрещать его значило бы делать докстринги
    беспредметными.
    """
    offences = [msg for path in _sources() if (msg := _single_discipline_offence(path))]
    assert not offences, (
        "Механика говорит словами одного раздела — читатель и модель примут\n"
        "частный случай за правило. Назовите роль («ответвление трассы»,\n"
        "«расчётная таблица») либо покажите, что наблюдение общее, примером\n"
        "из нескольких дисциплин:\n  " + "\n  ".join(offences))
    print(f"OK: ни один из {len(_sources())} файлов механики не привязан к одной дисциплине")
